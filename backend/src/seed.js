// First-run seed data: applications (FR-14.1), theme (FR-1.6), templates, paragraph library (FR-1.5),
// and a sample pre-ingestion hook (FR-13.2). Idempotent — only seeds empty collections.
import { collection, save } from './store.js';

export function seed() {
  if (collection('applications').length === 0) {
    collection('applications').push(
      { id: 'app_default', name: 'Statements', description: 'Billing & invoices' },
      { id: 'app_letters', name: 'Ad-hoc Letters', description: 'Content Author correspondence (FR-1.9)' },
    );
    save('applications');
  }

  if (collection('themes').length === 0) {
    collection('themes').push({
      id: 'theme_brand',
      name: 'Acme Brand',
      color: '#1a3c6e',
      font: 'Helvetica',
      blockStyle: { fontSize: 11 },
      footerText: 'Acme Corp · This communication was generated by NextGen-CCM · {{customer_id}}',
    });
    save('themes');
  }

  if (collection('templates').length === 0) {
    collection('templates').push(
      {
        id: 'tpl_invoice',
        name: 'Customer Invoice',
        applicationId: 'app_default',
        themeId: 'theme_brand',
        version: 1,
        status: 'approved',
        pageSetup: { size: 'A4', orientation: 'portrait', nUp: 1, watermark: null, duplex: true },
        lookups: [{ name: 'product', source: 'products.json', key: '{{product_code}}' }],
        blocks: [
          { id: 'header', type: 'text', text: 'ACME CORP — INVOICE', locked: true, style: { fontSize: 18, bold: true } },
          { id: 'greeting', type: 'text', text: 'Dear {{name}},', editable: true },
          { id: 'body', type: 'text', text: 'Your invoice {{invoice_number}} for plan "{{lookup.product.title}}" is due on {{due_date}}. Amount: {{amount}} {{currency}}.', editable: true },
          { id: 'promo', type: 'text', text: 'Special offer: {{lookup.product.promo}}', rule: { field: 'lookup.product.promo', op: 'exists' } },
          { id: 'ca_notice', type: 'text', text: 'California residents: see additional state disclosures at acme.example/ca.', rule: { field: 'state', op: 'eq', value: 'CA' }, style: { fontSize: 9 } },
          { id: 'legal', type: 'text', text: 'This is a legally required notice. Do not modify. Questions: legal@acme.example', locked: true, style: { fontSize: 8, color: '#666666' } },
        ],
      },
      {
        id: 'tpl_letter_shell',
        name: 'Ad-hoc Letter Shell (Content Author)',
        applicationId: 'app_letters',
        themeId: 'theme_brand',
        version: 1,
        status: 'approved',
        pageSetup: { size: 'A4', orientation: 'portrait', nUp: 1, watermark: null },
        blocks: [
          { id: 'letterhead', type: 'text', text: 'ACME CORP — Customer Care', locked: true, style: { fontSize: 16, bold: true } },
          { id: 'salutation', type: 'text', text: 'Dear {{name}},', editable: true },
          { id: 'letter_body', type: 'text', text: '{{letter_body}}', editable: true },
          { id: 'signoff', type: 'text', text: 'Sincerely,\n{{agent_name}}\nAcme Customer Care', editable: true },
          { id: 'legal', type: 'text', text: 'Acme Corp is a registered entity. This letter is recorded for compliance purposes.', locked: true, style: { fontSize: 8, color: '#666666' } },
        ],
      },
      {
        id: 'tpl_bizcard',
        name: 'Business Card (N-up demo)',
        applicationId: 'app_default',
        themeId: 'theme_brand',
        version: 1,
        status: 'approved',
        pageSetup: { size: 'A4', orientation: 'portrait', nUp: 10, watermark: null },
        blocks: [
          { id: 'name', type: 'text', text: '{{name}}', style: { fontSize: 14, bold: true } },
          { id: 'role', type: 'text', text: '{{role}}' },
          { id: 'contact', type: 'text', text: '{{email}} · {{phone}}', style: { fontSize: 9 } },
        ],
      },
    );
    save('templates');
  }

  if (collection('paragraphs').length === 0) {
    collection('paragraphs').push(
      { id: 'p_apology', applicationId: 'app_letters', title: 'Service apology', text: 'We sincerely apologize for the inconvenience you experienced. We have reviewed your case and taken corrective action.' },
      { id: 'p_goodwill', applicationId: 'app_letters', title: 'Goodwill credit', text: 'As a gesture of goodwill, we have applied a credit to your account, which will appear on your next statement.' },
      { id: 'p_escalation', applicationId: 'app_letters', title: 'Escalation contact', text: 'If you have further concerns, contact our resolution desk at care@acme.example or +1-800-555-0100.' },
    );
    save('paragraphs');
  }

  if (collection('hooks').length === 0) {
    collection('hooks').push({
      id: 'hook_normalize_names',
      applicationId: '*',
      stage: 'pre_ingestion',
      enabled: true,
      code: `
        // Normalize driver-file records: trim + title-case names (FR-13.2 demo)
        if (ctx.data && Array.isArray(ctx.data.records)) {
          ctx.data.records = ctx.data.records.map(r => ({
            ...r,
            name: r.name ? String(r.name).trim().replace(/\\w\\S*/g, t => t[0].toUpperCase() + t.slice(1).toLowerCase()) : r.name,
          }));
          log('normalized ' + ctx.data.records.length + ' records');
        }
      `,
    });
    save('hooks');
  }

  if (collection('fonts').length === 0) {
    save('fonts'); // empty registry file; drop TTFs into samples/fonts and register via data/fonts.json
  }
}
